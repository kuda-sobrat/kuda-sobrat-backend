Проанализируй предоставленный текст и найди все мероприятия. Верни **только** JSON следующего формата без дополнительного текста:

{
"is_event": [true|false],
"events": [
{
"name": "string",
"description": "string",
"start_datetime": "YYYY-MM-DD HH:MM" или null,
"end_datetime": "YYYY-MM-DD HH:MM" или null,
"location": "string" или null,
"is_paid": [true|false],
"price": number или null
},
...
]
}

**Текущая дата**: {{now()->year}}-{{now()->month}}-{{now()->day}}
**Местоположение сообщества**:
"{{ $communityLocation ?? 'НЕ ОПРЕДЕЛЕНО' }}"

**Требования**:

- Определи все мероприятия, комбинируя каждую указанную дату с каждым временем.
- Если на одну дату указано несколько времён, каждое сочетание даты и времени считается отдельным мероприятием.
- **is_event**: `true`, если в тексте есть мероприятия, иначе `false`.
- **events**: массив мероприятий.
- **name**: развернутое полное название мероприятия.
- **description**: развернутое описание мероприятия.
- **start_datetime**: дата и время начала мероприятия в формате "YYYY-MM-DD HH:MM". Если не указано, установи `null`.
- **end_datetime**: дата и время окончания мероприятия в формате "YYYY-MM-DD HH:MM". Если не указано, установи `null`.
- **location**: место проведения в формате "ул. Улица..." или "г. Воронеж, ...". Если информации недостаточно, установи `null`.
- **is_paid**: `true`, если мероприятие платное, иначе `false`.
- **price**: стоимость мероприятия числом. Если не указано, установи `null`.

**Важно**:

- Не придумывай информацию, которой нет в тексте.
- Исключай акции и рекламу магазинов.
- Если информацию определить невозможно, соответствующее поле должно быть `null`.
- Не добавляй никакого дополнительного текста или комментариев. Верни **только** требуемый JSON.
- При наличии нескольких дат и времён, создай отдельное мероприятие для каждой комбинации.
- Все даты считай происходящими в текущем году ({{now()->year}}).
- **description** для каждого мероприятия верни развернутым.
- **Время окончания мероприятия**: если не указано, установи `null`, кроме случая с лекцией (где время окончания указано).

