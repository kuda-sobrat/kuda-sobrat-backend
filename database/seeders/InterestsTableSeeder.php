        // Рекурсивная функция для добавления интересов
        $addInterests = function ($interests, $parentId = null) use (&$addInterests, &$interestsMap) {
            foreach ($interests as $interest) {
                $name = $interest['name'];
                $isPaid = $interest['is_paid'] ?? false;

                // Проверяем, существует ли уже интерес
                if (isset($interestsMap[$name])) {
                    $interestId = $interestsMap[$name];

                    // Обновляем флаг is_paid, если хотя бы в одной категории он true
                    if ($isPaid && !DB::table('interests')->where('id', $interestId)->value('is_paid')) {
                        DB::table('interests')->where('id', $interestId)->update(['is_paid' => true]);
                    }

                    // Если есть родитель, проверяем и добавляем связь
                    if (!is_null($parentId)) {
                        $exists = DB::table('interest_relations')
                            ->where('interest_id', $interestId)
                            ->where('parent_interest_id', $parentId)
                            ->exists();

                        if (!$exists) {
                            DB::table('interest_relations')->insert([
                                'interest_id' => $interestId,
                                'parent_interest_id' => $parentId,
                            ]);
                        }
                    }
                } else {
                    // Добавляем интерес в таблицу
                    $interestId = DB::table('interests')->insertGetId([
                        'name' => $name,
                        'description' => $name,
                        'is_paid' => $isPaid,
                    ]);

                    $interestsMap[$name] = $interestId;

                    // Добавляем связь с родителем
                    if (!is_null($parentId)) {
                        DB::table('interest_relations')->insert([
                            'interest_id' => $interestId,
                            'parent_interest_id' => $parentId,
                        ]);
                    }
                }

                // Обрабатываем детей рекурсивно
                if (isset($interest['children'])) {
                    $addInterests($interest['children'], $interestId);
                }
            }
        };

        // Запускаем добавление интересов
        $addInterests($interestsData);
